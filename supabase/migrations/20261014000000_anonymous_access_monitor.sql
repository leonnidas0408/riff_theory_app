create extension if not exists pgcrypto;

create table if not exists public.access_visits (
  id bigint generated by default as identity primary key,
  browser_id text not null,
  session_id text not null,
  created_at timestamptz not null default now()
);

create index if not exists access_visits_created_at_idx on public.access_visits (created_at desc);
create index if not exists access_visits_browser_created_at_idx on public.access_visits (browser_id, created_at desc);

alter table public.access_visits enable row level security;

create or replace function public.register_anonymous_access(
  p_browser_id text,
  p_browser_signature text,
  p_session_id text
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  now_utc timestamptz := now();
  recent_count integer;
  daily_count integer;
begin
  if coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' then
    raise exception 'server_only';
  end if;
  if p_browser_id is null or length(p_browser_id) < 16 or length(p_browser_id) > 128 then
    raise exception 'invalid_browser_id';
  end if;
  if p_session_id is null or length(p_session_id) < 16 or length(p_session_id) > 128 then
    raise exception 'invalid_session_id';
  end if;

  select count(*) into recent_count from public.access_visits
    where browser_id = p_browser_id and created_at >= now_utc - interval '5 minutes';
  if recent_count >= 30 then return jsonb_build_object('accepted', false, 'reason', 'rate_5m'); end if;

  select count(*) into daily_count from public.access_visits
    where browser_id = p_browser_id
      and (created_at at time zone 'America/Sao_Paulo')::date = (now_utc at time zone 'America/Sao_Paulo')::date;
  if daily_count >= 300 then return jsonb_build_object('accepted', false, 'reason', 'rate_day'); end if;

  insert into public.access_visits (browser_id, session_id) values (p_browser_id, p_session_id);
  return jsonb_build_object('accepted', true);
end;
$$;

revoke all on function public.register_anonymous_access(text, text, text) from public, anon, authenticated;
grant execute on function public.register_anonymous_access(text, text, text) to service_role;
revoke all on table public.access_visits from anon, authenticated;
